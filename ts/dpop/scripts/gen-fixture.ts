// Writes go/lib/dpop/testdata/ts_proofs.json: proofs made by this package,
// which the Go verifier checks in TestTSProofsVerify (go/lib/dpop). It is the
// cross-language test: the TypeScript client and the Go server agree on the
// JWS, the JWK, the thumbprint, ath, htu and the nonce only if the Go test
// passes on what this wrote.
//
// Regenerate (from ts/dpop, in a Node >= 20 environment):
//
//     npm run fixture
//
// then run the Go test and commit both. Every run makes a new key and new
// proofs; the Go test needs no particular values, only that they verify.
// `npm test` never runs this file.

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { it } from "vitest";

import { createDpopFetch } from "../src/fetch";
import { jwkThumbprint } from "../src/jwk";
import { loadOrCreateKey, MemoryKeyStore } from "../src/key";
import { createProof } from "../src/proof";
import { issueStreamTicket } from "../src/ticket";

const ORIGIN = "https://api.example.com";
const NONCE = "ts-fixture-nonce";
const TOKEN = "fixture-access-token.Kz~8mXK1";
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../../go/lib/dpop/testdata/ts_proofs.json",
);

interface Case {
  name: string;
  method: string;
  /** The request path as the server sees it, query included. */
  path: string;
  /** The access token the request carries, "" for none (a sign-in request). */
  token: string;
  proof: string;
}

it("writes the cross-language fixture", async () => {
  const store = new MemoryKeyStore();
  const key = await loadOrCreateKey(store);
  const cases: Case[] = [];
  const direct = async (name: string, method: string, url: string, path: string, token: string) => {
    cases.push({
      name,
      method,
      path,
      token,
      proof: await createProof(key, { htm: method, htu: url, accessToken: token, nonce: NONCE }),
    });
  };

  await direct(
    "bound GET with a query",
    "GET",
    `${ORIGIN}/v1/things?page=2#top`,
    "/v1/things?page=2",
    TOKEN,
  );
  await direct("unbound POST, no token", "POST", `${ORIGIN}/v1/sign-in`, "/v1/sign-in", "");
  await direct(
    "htu with upper case and default port",
    "DELETE",
    "HTTPS://API.Example.com:443/v1/things/42",
    "/v1/things/42",
    TOKEN,
  );
  await direct(
    "percent-encoded path",
    "PUT",
    `${ORIGIN}/v1/files/a%20b%2Fc`,
    "/v1/files/a%20b%2Fc",
    TOKEN,
  );

  // Through the fetch wrapper and the ticket helper: the first attempt has
  // no nonce and is challenged, the retry carries the fixture nonce.
  const captured: string[] = [];
  const server = (input: RequestInfo | URL): Promise<Response> => {
    const req = input as Request;
    const proof = req.headers.get("DPoP") ?? "";
    captured.push(proof);
    if (captured.length === 1) {
      return Promise.resolve(
        new Response("{}", {
          status: 401,
          headers: { "WWW-Authenticate": 'DPoP error="use_dpop_nonce"', "DPoP-Nonce": NONCE },
        }),
      );
    }
    return Promise.resolve(
      new Response(JSON.stringify({ ticket: "t", expires_in: 30 }), {
        headers: { "Content-Type": "application/json" },
      }),
    );
  };
  const f = createDpopFetch({
    origins: [ORIGIN],
    keyStore: store,
    getToken: () => TOKEN,
    fetch: server,
  });
  await issueStreamTicket(f, ORIGIN);
  if (captured.length !== 2) throw new Error(`want 2 attempts, got ${captured.length}`);
  cases.push({
    name: "fetch wrapper retry, ticket request",
    method: "POST",
    path: "/api/ws/ticket",
    token: TOKEN,
    proof: captured[1]!,
  });

  // Thumbprints the Go side recomputes: this run's key and the RFC 9449 key.
  const rfc9449 = {
    kty: "EC",
    crv: "P-256",
    x: "l8tFrhx-34tV3hRICRDY9zCkDlpBhF42UQUfWVAWBFs",
    y: "9VE4jf_Ok_o64zbTTlcuNJajHmt6v9TDVrU0CdvGRDA",
  };
  const fixture = {
    comment:
      "Generated by ts/dpop (npm run fixture); verified by TestTSProofsVerify. Regenerate with that command, then commit.",
    origin: ORIGIN,
    nonce: NONCE,
    jwk: key.jwk,
    thumbprint: key.thumbprint,
    cases,
    thumbprints: [
      { jwk: key.jwk, thumbprint: await jwkThumbprint({ ...key.jwk }) },
      { jwk: rfc9449, thumbprint: await jwkThumbprint(rfc9449) },
    ],
  };
  await writeFile(OUT, JSON.stringify(fixture, null, 2) + "\n");
});
