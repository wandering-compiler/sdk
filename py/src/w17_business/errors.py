"""Errors that say one thing to an operator and another to a person.

The Python twin of ``grpcerr.ForUser`` (sdk/go/core/grpcerr): the gRPC status
carries the OPERATOR's copy, prefixed with the method (``Svc.Method: <dev>``),
and a ``w17.ErrorDetail{code, message, field}`` carries the caller's sentence,
which the gateway renders. Encoded as Go encodes it: a ``google.rpc.Status`` in
``grpc-status-details-bin`` with the detail packed as
``type.googleapis.com/w17.ErrorDetail``.

The message is the author's own text: translation catalogs are not part of the
first version of the non-Go SDKs.

How the runtime answers an exception a handler raises:

- a ``GRPCError`` (``for_user``'s, or one a storage call raised and the handler
  let through) goes out as it is, details included — Go returns a storage
  status unchanged too;
- an SDK error (``DistxError``, ``NoPrincipalError``, ``ConfigError``) is a Go
  *returned* error: ``UNKNOWN`` with its message;
- anything else is a Go *panic*: reported, and answered ``INTERNAL``
  ``"<method>: internal error"`` — the exception text never reaches the caller.
"""

from __future__ import annotations

from grpclib.const import Status
from grpclib.encoding.base import StatusDetailsCodecBase
from grpclib.exceptions import GRPCError
from google.protobuf import any_pb2

from .descriptors import default_pool

__all__ = ["UserError", "for_user", "error_detail", "Status"]


def _status(code: Status | int | str) -> Status:
    if isinstance(code, Status):
        return code
    if isinstance(code, str):
        return Status[code.upper()]
    return Status(code)


def ErrorDetail(**kw):  # noqa: N802 — a message constructor
    """``w17.ErrorDetail(code=, message=, field=)``."""
    return default_pool().message("w17.ErrorDetail")(**kw)


class UserError(GRPCError):
    """A status with a ``w17.ErrorDetail``. Build it with ``for_user``.

    ``dev`` is the operator's copy; the runtime prefixes it with the method
    being served (``Svc.Method: dev``) when the error leaves the handler, as
    Go's ``method`` argument does."""

    def __init__(self, status: Status, dev: str, detail) -> None:
        super().__init__(status, dev, [detail])
        self.dev = dev
        self.detail = detail


def for_user(
    code: Status | int | str,
    detail_code: str,
    message: str,
    field: str = "",
    *,
    dev: str | None = None,
) -> UserError:
    """The error a handler raises to refuse with a sentence for a person.

        raise for_user(Status.FAILED_PRECONDITION, "SUBSCRIPTION_INACTIVE",
                       "This subscription is not active.")

    ``detail_code`` is what a client dispatches on, ``message`` the sentence it
    shows, ``field`` the request field it is about ("" for none). ``dev`` is the
    operator's copy for logs and Sentry; it defaults to ``message``."""
    st = _status(code)
    detail = ErrorDetail(code=detail_code, message=message, field=field)
    return UserError(st, message if dev is None else dev, detail)


def error_detail(err: GRPCError):
    """The ``w17.ErrorDetail`` an error carries, or None."""
    name = "w17.ErrorDetail"
    for d in err.details or ():
        if getattr(getattr(d, "DESCRIPTOR", None), "full_name", "") == name:
            return d
    return None


class StatusDetailsCodec(StatusDetailsCodecBase):
    """grpclib's status-details codec, resolving detail types through the SDK's
    descriptor pool.

    grpclib's own ``ProtoStatusDetailsCodec`` looks a detail's type up in the
    protobuf symbol database, which knows only classes generated by protoc;
    the w17 messages here are built at runtime from descriptor sets, so its
    lookup would answer ``Unknown('w17.ErrorDetail')`` and a storage error's
    detail would be lost on the way through this tier. The encoding is the
    same: a ``google.rpc.Status`` with the details packed as ``Any``."""

    def encode(self, status: Status, message: str | None, details) -> bytes:
        from google.rpc import status_pb2

        st = status_pb2.Status(code=status.value, message=message or "")
        for d in details or ():
            if isinstance(d, any_pb2.Any):
                st.details.add().CopyFrom(d)  # relayed as received
            else:
                st.details.add().Pack(d)
        return st.SerializeToString()

    def decode(self, status: Status, message: str | None, data: bytes):
        from google.rpc import status_pb2

        st = status_pb2.Status.FromString(data)
        out = []
        pool = default_pool()
        for any_ in st.details:
            try:
                cls = pool.message(any_.TypeName())
            except KeyError:
                out.append(any_)  # kept packed: unknown here, maybe known downstream
                continue
            d = cls()
            any_.Unpack(d)
            out.append(d)
        return out
